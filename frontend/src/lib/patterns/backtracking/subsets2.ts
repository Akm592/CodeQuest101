type Input = number[];

function run(input: Input): PatternStep[] {
  const nums = [...input].sort((a, b) => a - b);
  const t = new RecTree();
  const frames: Frame[] = [];
  const res: number[][] = [];
  const cur: number[] = [];
  const path: string[] = [];
  let ops = 0;
  let span: [number, number] = [-1, -1];
  const push = (stage: string, explanation: string, node?: string, extra: Partial<PatternStep> = {}) =>
    frames.push({
      stage,
      explanation,
      rows: [
        row("nums, sorted", nums, Object.fromEntries(nums.map((_, j) => [j, j === span[0] ? "current" : j > span[0] && j <= span[1] ? "compare" : undefined])), Object.fromEntries(nums.map((_, j) => [j, `i=${j}`]))),
        row("subset so far", cur),
        row("subsets found", res.map(showList), Object.fromEntries(res.map((_, j) => [j, j === res.length - 1 && stage === "leaf" ? "found" : undefined]))),
      ],
      vars: [{ name: "subsets found", value: String(res.length), tone: "found" }],
      ops,
      ...at(t, node, path),
      ...extra,
    });
  const root = t.add("·", undefined, "[]");
  path.push(root);
  push("start", `Sort first, so equal numbers sit together: ${show(nums)}. Then decide number by number as in Subsets, with one change: when you leave a number out, leave out all its copies too. Otherwise “take the first 2” and “take the second 2” would build the same subset twice.`, root);
  const dfs = (k: number, node: string) => {
    ops++;
    if (k === nums.length) {
      res.push([...cur]);
      t.found.push(node);
      span = [-1, -1];
      push("leaf", `Every number is decided: record ${showList(cur)}.`, node);
      return;
    }
    span = [k, k];
    cur.push(nums[k]);
    const a = t.add(`+${nums[k]}`, node, showList(cur));
    path.push(a);
    push("take", `Put ${nums[k]} in: ${showList(cur)}.`, a);
    dfs(k + 1, a);
    path.pop();
    cur.pop();
    let j = k;
    while (j + 1 < nums.length && nums[j + 1] === nums[k]) j++;
    span = [k, j];
    const b = t.add(`−${nums[k]}`, node, showList(cur));
    path.push(b);
    push(
      "skip",
      j > k ? `Undo, then leave ${nums[k]} out, and skip its ${j - k} other cop${j - k === 1 ? "y" : "ies"} as well (index ${k + 1}${j > k + 1 ? `…${j}` : ""}). Any subset with a ${nums[k]} came from the left branch already.` : `Undo, then leave ${nums[k]} out.`,
      b,
    );
    dfs(j + 1, b);
    path.pop();
  };
  dfs(0, root);
  path.length = 0;
  span = [-1, -1];
  push("done", `Done: ${res.length} different subsets, none repeated.`, undefined, { done: true, answer: showLists(canonLists(res, true)) });
  return finish(t, frames, "decision tree: −x skips every copy of x");
}

/** The slow way: build all 2^n subsets, then throw away repeats. */
function slow(nums: Input) {
  const seen = new Map<string, number[]>();
  let ops = 0;
  for (let m = 0; m < 1 << nums.length; m++) {
    const s = nums.filter((_, j) => m & (1 << j)).sort((a, b) => a - b);
    ops += nums.length;
    seen.set(s.join(","), s);
  }
  return { answer: showLists(canonLists([...seen.values()], true)), ops };
}

