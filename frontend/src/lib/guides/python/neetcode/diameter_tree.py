class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val, self.left, self.right = val, left, right


def build(level):
    """A tree from LeetCode's level order, e.g. [3, 9, 20, None, None, 15, 7]."""
    if not level or level[0] is None:
        return None
    root = TreeNode(level[0])
    queue, i = [root], 1
    while queue and i < len(level):
        node = queue.pop(0)
        for side in ("left", "right"):
            if i < len(level) and level[i] is not None:
                setattr(node, side, TreeNode(level[i]))
                queue.append(getattr(node, side))
            i += 1
    return root


def to_level(root):
    out, queue = [], [root]
    while queue:
        node = queue.pop(0)
        out.append(node.val if node else None)
        if node:
            queue += [node.left, node.right]
    while out and out[-1] is None:
        out.pop()
    return out


def diameter_of_binary_tree(root):
    """Edges on the longest path between any two nodes. The longest path
    through a node goes down its left subtree and down its right one, so it's
    height(left) + height(right). One DFS computes every height. O(n)."""
    best = 0

    def height(node):
        nonlocal best
        if not node:
            return 0
        left, right = height(node.left), height(node.right)
        best = max(best, left + right)  # longest path that bends at this node
        return 1 + max(left, right)

    height(root)
    return best


print(diameter_of_binary_tree(build([1, 2, 3, 4, 5])))  # 3 (4 → 2 → 1 → 3)
